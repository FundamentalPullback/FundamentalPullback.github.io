// Deterministically validate/compile author-selected evidence. Does not generate opinions,
// fetch market data, call an LLM, revise status, or publish. Run on every publication.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),load=require('./load-stock-profiles.cjs');
const {c,engine,profiles,reports}=load(root);
const migrationFile=root+'/tools/research-balance-legacy.json';
const legacy=JSON.parse(fs.readFileSync(migrationFile,'utf8'));
const reportBy=Object.fromEntries(reports.map(r=>[r.id,r]));
const seen=new Set();
for(const r of legacy){
 const key=r.ticker+'|'+r.reportId;if(seen.has(key))throw Error('Duplicate research balance: '+key);seen.add(key);
 const report=reportBy[r.reportId];if(!report)throw Error('Missing source report: '+key);
 if(r.sourceFingerprint===engine.balanceFingerprint(report.text)&&!engine.balanceStructured(r,report,r.ticker,r.asOf,'verified-migration'))throw Error('Invalid evidence: '+key);
 // Retain invalidated fingerprints, so the UI explicitly reports stale evidence.
}
c.window.FP_RESEARCH_BALANCE={records:legacy};
const states=profiles.map(p=>({ticker:p.ticker,completed:!!p.latestCompleted,...engine.researchBalance(p)}));
// New or revised completed research may not silently omit its evidence summary.
// An explicit reviewed unavailable reason is allowed; newer incomplete research stays pending.
const blocked=states.filter(x=>x.completed&&!['ready','newer-analysis','unavailable'].includes(x.status));
if(blocked.length)throw Error('Completed research needs reviewed pros/cons or prosConsUnavailable metadata: '+blocked.map(x=>x.ticker+':'+x.sourceId+':'+x.status).join(', '));
const coverage={profileCount:profiles.length,completedResearchCount:states.filter(x=>x.completed).length,withBothSides:states.filter(x=>x.status==='ready'&&x.pros.length&&x.cons.length).length,withOneSide:states.filter(x=>x.status==='ready'&&(!x.pros.length||!x.cons.length)).length,pendingOrUnavailable:states.filter(x=>x.status!=='ready').length,byStatus:{}};
for(const x of states)coverage.byStatus[x.status]=(coverage.byStatus[x.status]||0)+1;
const output={schema:'fp.research-balance-catalog.v1',coverage,records:legacy};
fs.writeFileSync(root+'/data/research-balance.js','/* Generated by tools/build-stock-balance.cjs. Evidence-backed research, not trade authorization. */\nwindow.FP_RESEARCH_BALANCE='+JSON.stringify(output)+';\n');
console.log('Research balance coverage:',JSON.stringify(coverage));
const missing=states.filter(x=>x.completed&&x.status!=='ready');console.log('Explicit pending:',missing.map(x=>x.ticker+':'+x.status).join(', '));
